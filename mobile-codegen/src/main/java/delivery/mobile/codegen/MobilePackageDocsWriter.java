package delivery.mobile.codegen;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * M4-07: generated README, properties examples, self-hosted CI example, portal display stub notes.
 */
public final class MobilePackageDocsWriter {

    private MobilePackageDocsWriter() {}

    public static void writeAll(Path projectRoot) throws Exception {
        writeReadme(projectRoot);
        writePropertiesExample(projectRoot);
        writeCiExample(projectRoot);
        writePortalDisplayStub(projectRoot);
    }

    public static void writeReadme(Path projectRoot) throws Exception {
        Path readme = projectRoot.resolve("README.md");
        String body = """
                # Keel Mobile Framework Package

                Generated by Keel MobileCodeWriter (ANDROID).

                ## Prerequisites
                - JDK 21+
                - Maven 3.9+
                - Local Appium server + Android device/emulator (`mobile.udid` required)
                - Secrets via env `KEEL_SECRET_*` or gitignored `secrets.properties` (never commit)

                ## Configure
                1. Copy `src/test/resources/config/appium.properties.example` → `appium.properties` and set `mobile.udid`, `mobile.serverUrl`, app source.
                2. Copy `src/test/resources/config/secrets.example.properties` → `secrets.properties` (gitignored) or export `KEEL_SECRET_*`.
                3. Missing required properties fail clearly via `PropertyReader.required` / `MobileProperties.require`.

                ## Run
                ```bash
                mvn test
                ```

                ## Not included
                - APK binaries, runner tokens, credentials, machine paths, helper unit tests, Surefire/Allure output

                ## Auth
                `BaseMobileTest.authSetupIfConfigured()` → `AuthCoordinator` (mode/profile revision refs only).
                """;
        Files.writeString(readme, body, StandardCharsets.UTF_8);
    }

    public static void writePropertiesExample(Path projectRoot) throws Exception {
        Path cfg = projectRoot.resolve("src/test/resources/config");
        Files.createDirectories(cfg);
        Path example = cfg.resolve("appium.properties.example");
        if (!Files.exists(example)) {
            Files.writeString(example, """
                    mobile.platformName=Android
                    mobile.automationName=UiAutomator2
                    mobile.serverUrl=http://127.0.0.1:4723
                    mobile.udid=
                    mobile.deviceName=
                    mobile.appSource=INSTALLED
                    mobile.appPackage=
                    mobile.appActivity=
                    # mobile.auth.mode=LOGIN_UNDER_TEST
                    # mobile.auth.profileRevisionId=
                    """, StandardCharsets.UTF_8);
        }
    }

    public static void writeCiExample(Path projectRoot) throws Exception {
        Path ci = projectRoot.resolve("ci/github-actions");
        Files.createDirectories(ci);
        Files.writeString(ci.resolve("mobile-tests.yml.example"), """
                # Self-hosted device runner example — disabled by default.
                # Enable only when a labelled runner with Appium + device is available.
                name: mobile-tests
                on:
                  workflow_dispatch:
                jobs:
                  test:
                    runs-on: [self-hosted, mobile]
                    steps:
                      - uses: actions/checkout@v4
                      - uses: actions/setup-java@v4
                        with:
                          distribution: temurin
                          java-version: '21'
                      - name: Run tests
                        run: mvn -B test
                      - name: Upload Allure (optional)
                        if: always()
                        uses: actions/upload-artifact@v4
                        with:
                          name: allure-results
                          path: allure-results
                # Sticky PR comment with hidden marker: customer opt-in only — not enabled here.
                """, StandardCharsets.UTF_8);
    }

    public static void writePortalDisplayStub(Path projectRoot) throws Exception {
        Path docs = projectRoot.resolve("docs");
        Files.createDirectories(docs);
        Files.writeString(docs.resolve("PORTAL_PACKAGE_DISPLAY.md"), """
                # Portal package display (stub)

                Hooks for portal UI (M4-07):
                - Show package version + fingerprint from `docs/package-manifest.json`
                - List generated vs TODO case counts from `docs/MOBILE_COVERAGE.md`
                - Never display secret values, APK bytes, udid, or machine paths
                - Download bound to exact package version (MobileProofInvalidation.downloadBound)

                This file is a stub until portal wire-up lands.
                """, StandardCharsets.UTF_8);
    }
}
