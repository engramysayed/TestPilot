package delivery.mobile.codegen;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Emits non-secret owner+phase properties. Secret-ref keys are omitted entirely
 * (resolved at runtime via customer SecretResolver / env / excluded file).
 */
public final class MobileTestdataWriter {

    public static final String RELATIVE_PATH = "src/test/resources/test-data/mobile-testdata.properties";

    private MobileTestdataWriter() {}

    public static Path write(Path outputRoot, MobileTestdataKeys keys) throws Exception {
        if (outputRoot == null) {
            throw new IllegalArgumentException("outputRoot required");
        }
        if (keys == null) {
            keys = MobileTestdataKeys.empty();
        }
        Path out = outputRoot.resolve(RELATIVE_PATH);
        Files.createDirectories(out.getParent());

        Map<String, String> published = new TreeMap<>();
        for (Map.Entry<String, String> e : keys.valuesByKey().entrySet()) {
            if (keys.isSecretKey(e.getKey())) {
                continue;
            }
            if (e.getValue() == null) {
                continue;
            }
            published.put(e.getKey(), e.getValue());
        }

        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by MobileCodeWriter — non-secret testdata only.\n");
        sb.append("# Secrets: use SecretResolver (KEEL_SECRET_* / secrets.properties); never commit.\n");
        for (String name : new TreeSet<>(published.keySet())) {
            sb.append(escape(name)).append('=').append(escape(published.get(name))).append('\n');
        }
        Files.writeString(out, sb.toString(), StandardCharsets.UTF_8);
        return out;
    }

    private static String escape(String raw) {
        if (raw == null) {
            return "";
        }
        return raw.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r");
    }
}
