#!/usr/bin/env python3
"""Generate src/main/resources/static/css/keel-rtl.css: mirrors every physical left/right declaration of the portal
stylesheets under html[dir="rtl"]. Re-run after CSS changes:  python scripts/gen-rtl-css.py"""
import re, sys, os

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main', 'resources', 'static', 'css')
SOURCES = ['portal.css', 'keel-reskin.css', 'keel-layout.css', 'keel-theme-calm.css', 'keel-portal-enhancements.css',
           'keel-sidebar-roles.css', 'keel-credits.css', 'keel-mobile-ui.css']
PAIRS = {'margin-left': 'margin-right', 'padding-left': 'padding-right', 'left': 'right',
         'border-left': 'border-right', 'border-left-color': 'border-right-color',
         'border-left-width': 'border-right-width', 'border-left-style': 'border-right-style',
         'border-top-left-radius': 'border-top-right-radius',
         'border-bottom-left-radius': 'border-bottom-right-radius'}
for k, v in list(PAIRS.items()):
    PAIRS[v] = k
RESET = {'margin': '0', 'padding': '0', 'left': 'auto', 'right': 'auto', 'border': 'none'}


def reset_for(prop):
    if prop in ('left', 'right'):
        return 'auto'
    if prop.startswith('margin'):
        return '0'
    if prop.startswith('padding'):
        return '0'
    if 'radius' in prop:
        return '0'
    if prop in ('border-left', 'border-right'):
        return 'none'
    if prop.endswith('-width'):
        return '0'
    return 'initial'


def parse(css):
    """Yield (prelude, body) for each block; nested at-rules return nested lists."""
    items, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{':
                depth += 1
            elif css[k] == '}':
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if prelude.startswith('@media') or prelude.startswith('@supports'):
            items.append((prelude, parse(body)))
        elif prelude.startswith('@'):
            pass  # keyframes, font-face …
        else:
            items.append((prelude, body))
        i = k
    return items


def rtl_selector(sel):
    out = []
    for part in sel.split(','):
        p = part.strip()
        if not p:
            continue
        m = re.match(r'^html((?:\[[^\]]*\]|\.[\w-]+)*)(.*)$', p)
        if m:
            out.append('html[dir="rtl"]' + m.group(1) + m.group(2))
        elif p.startswith(':root'):
            out.append(':root[dir="rtl"]' + p[5:])
        else:
            out.append('html[dir="rtl"] ' + p)
    return ', '.join(out)


def mirror_decls(body):
    decls = []
    for d in body.split(';'):
        if ':' not in d:
            continue
        prop, val = d.split(':', 1)
        decls.append((prop.strip().lower(), val.strip()))
    props = {p: v for p, v in decls}
    out = []
    for p, v in decls:
        if p in PAIRS:
            other = PAIRS[p]
            out.append(f'{other}: {v}')
            if other not in props:
                out.append(f'{p}: {reset_for(p)}')
        elif p == 'text-align' and v.split()[0] in ('left', 'right'):
            out.append('text-align: ' + ('right' if v.startswith('left') else 'left') + v[len(v.split()[0]):])
        elif p == 'float' and v in ('left', 'right'):
            out.append('float: ' + ('right' if v == 'left' else 'left'))
    # de-duplicate keeping last
    seen, final = {}, []
    for d in out:
        seen[d.split(':')[0]] = d
    for d in out:
        if seen.get(d.split(':')[0]) == d and d not in final:
            final.append(d)
    return final


def emit(items, indent=''):
    lines = []
    for prelude, body in items:
        if isinstance(body, list):
            inner = emit(body, indent + '    ')
            if inner:
                lines.append(f'{indent}{prelude} {{')
                lines.extend(inner)
                lines.append(f'{indent}}}')
            continue
        decls = mirror_decls(body)
        if decls:
            lines.append(f'{indent}{rtl_selector(prelude)} {{ ' + '; '.join(decls) + '; }')
    return lines


def main():
    out = ['/* GENERATED by scripts/gen-rtl-css.py — do not edit by hand. Mirrors physical left/right rules for',
           '   Arabic (html[dir="rtl"]). Hand-written RTL tweaks go in the section at the end of this script. */', '']
    for name in SOURCES:
        path = os.path.join(ROOT, name)
        if not os.path.exists(path):
            continue
        css = re.sub(r'/\*.*?\*/', '', open(path, encoding='utf-8').read(), flags=re.S)
        block = emit(parse(css))
        if block:
            out.append(f'/* ---- {name} ---- */')
            out.extend(block)
            out.append('')
    out += [
        '/* ---- hand-written ---- */',
        'html[dir="rtl"] body { font-family: "Segoe UI", Tahoma, "Noto Naskh Arabic", "Noto Sans Arabic", system-ui, sans-serif; }',
        'html[dir="rtl"] code, html[dir="rtl"] pre, html[dir="rtl"] .mono, html[dir="rtl"] input[type="url"],',
        'html[dir="rtl"] input[type="email"] { direction: ltr; unicode-bidi: isolate; }',
        'html[dir="rtl"] table th, html[dir="rtl"] table td { text-align: right; }',
        '',
    ]
    open(os.path.join(ROOT, 'keel-rtl.css'), 'w', encoding='utf-8').write('\n'.join(out))
    print('keel-rtl.css:', len(out), 'lines')


if __name__ == '__main__':
    main()
