package delivery.portal.roles;

import org.h2.jdbcx.JdbcDataSource;
import org.testng.Assert;
import org.testng.annotations.Test;

import java.sql.Connection;
import java.sql.Statement;

public class RolesSchemaMigrationTest {
    @Test
    public void reentryIsIdempotentAndAddsApprovalColumns() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:roles-mig-" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        ds.setPassword("");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("""
                    CREATE TABLE portal_users (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      email VARCHAR(255), password_hash VARCHAR(255), role VARCHAR(16), enabled BOOLEAN
                    )
                    """);
            s.execute("""
                    CREATE TABLE jobs (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      job_id VARCHAR(80), project_id VARCHAR(64), owner_user_id BIGINT,
                      mode VARCHAR(16), status VARCHAR(32), created_at TIMESTAMP
                    )
                    """);
        }
        Assert.assertTrue(RolesSchemaMigration.migrate(ds));
        Assert.assertFalse(RolesSchemaMigration.migrate(ds));
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            Assert.assertTrue(RolesSchemaMigration.exists(c, "roles", null));
            Assert.assertTrue(RolesSchemaMigration.exists(c, "role_permissions", null));
            Assert.assertTrue(RolesSchemaMigration.exists(c, "portal_users", "role_id"));
            Assert.assertTrue(RolesSchemaMigration.exists(c, "portal_users", "approval_status"));
            Assert.assertTrue(RolesSchemaMigration.exists(c, "jobs", "account_scoped"));
        }
    }
}
