package delivery.mobile.db;

import org.h2.jdbcx.JdbcDataSource;
import org.testng.Assert;
import org.testng.annotations.Test;

import java.sql.Connection;
import java.sql.Statement;

/** M1-01: migration reentry without Spring Boot. */
public class MobileSchemaMigrationTest {
    @Test
    public void reentryIsIdempotentAndBackfillsPlatform() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mobile-mig-" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        ds.setPassword("");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE projects (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id VARCHAR(64), name VARCHAR(255), owner_user_id BIGINT, latest_version INT)");
            s.execute("INSERT INTO projects (project_id, name, owner_user_id, latest_version) VALUES ('prj_1','N',1,0)");
        }
        Assert.assertTrue(MobileSchemaMigration.migrate(ds));
        Assert.assertFalse(MobileSchemaMigration.migrate(ds)); // reentry — no structural change required
        try (Connection c = ds.getConnection(); Statement s = c.createStatement();
             var rs = s.executeQuery("SELECT platform FROM projects WHERE project_id='prj_1'")) {
            Assert.assertTrue(rs.next());
            Assert.assertEquals(rs.getString(1), "WEB");
        }
    }
}
