package delivery.portal.roles;

import org.springframework.stereotype.Component;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

/**
 * Additive schema for roles / role_permissions / portal_users.role_id + approval + jobs.account_scoped.
 * Idempotent; safe reentry. Hibernate ddl-auto may also create entities on fresh DBs.
 */
@Component("rolesSchemaMigration")
public class RolesSchemaMigration {
    private final boolean changed;

    public RolesSchemaMigration(DataSource dataSource) throws Exception {
        this.changed = migrate(dataSource);
    }

    public boolean appliedChange() {
        return changed;
    }

    public static boolean migrate(DataSource dataSource) throws Exception {
        try (Connection c = dataSource.getConnection()) {
            boolean changed = false;
            changed |= ensureTable(c, """
                    CREATE TABLE roles (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      role_id VARCHAR(64) NOT NULL,
                      name VARCHAR(128) NOT NULL,
                      description VARCHAR(512),
                      system_role BOOLEAN NOT NULL DEFAULT FALSE,
                      created_at TIMESTAMP NOT NULL,
                      CONSTRAINT uk_roles_role_id UNIQUE (role_id),
                      CONSTRAINT uk_roles_name UNIQUE (name)
                    )
                    """);
            changed |= ensureTable(c, """
                    CREATE TABLE role_permissions (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      role_id VARCHAR(64) NOT NULL,
                      permission VARCHAR(64) NOT NULL,
                      CONSTRAINT uk_role_permission UNIQUE (role_id, permission)
                    )
                    """);
            if (exists(c, "portal_users", null)) {
                changed |= addColumn(c, "portal_users", "role_id", "VARCHAR(64)");
                changed |= addColumn(c, "portal_users", "approval_status",
                        "VARCHAR(32) DEFAULT 'PENDING_APPROVAL'");
                changed |= addColumn(c, "portal_users", "approved_at", "TIMESTAMP");
                changed |= addColumn(c, "portal_users", "approved_by_user_id", "BIGINT");
                try (Statement s = c.createStatement()) {
                    s.executeUpdate("""
                            UPDATE portal_users SET approval_status = 'PENDING_APPROVAL'
                            WHERE approval_status IS NULL OR TRIM(approval_status) = ''
                            """);
                }
            }
            if (exists(c, "jobs", null)) {
                changed |= addColumn(c, "jobs", "account_scoped", "BOOLEAN DEFAULT FALSE");
            }
            return changed;
        }
    }

    private static boolean ensureTable(Connection c, String ddl) throws Exception {
        String name = tableNameFromCreate(ddl);
        if (exists(c, name, null)) {
            return false;
        }
        try (Statement s = c.createStatement()) {
            s.execute(ddl);
        }
        return true;
    }

    private static String tableNameFromCreate(String ddl) {
        String u = ddl.toUpperCase();
        int i = u.indexOf("CREATE TABLE");
        String rest = ddl.substring(i + "CREATE TABLE".length()).trim();
        return rest.split("\\s+")[0].replace("(", "").trim();
    }

    private static boolean addColumn(Connection c, String table, String column, String typeSql)
            throws Exception {
        if (exists(c, table, column)) {
            return false;
        }
        try (Statement s = c.createStatement()) {
            s.execute("ALTER TABLE " + table + " ADD COLUMN " + column + " " + typeSql);
        }
        return true;
    }

    public static boolean exists(Connection c, String table, String column) throws Exception {
        try (ResultSet rs = c.getMetaData().getColumns(null, null, table.toUpperCase(),
                column == null ? null : column.toUpperCase())) {
            if (rs.next()) {
                return true;
            }
        }
        try (ResultSet rs = c.getMetaData().getColumns(null, null, table.toLowerCase(),
                column == null ? null : column.toLowerCase())) {
            return rs.next();
        }
    }
}
