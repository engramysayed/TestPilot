package delivery.mobile.db;

import org.springframework.boot.autoconfigure.orm.jpa.EntityManagerFactoryDependsOnPostProcessor;
import org.springframework.stereotype.Component;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

/**
 * M1-01/M1-04 additive migration: {@code projects.platform} (+ backfill WEB) and mobile tables when absent.
 * M1-04 adds {@code mobile_devices.fence_seq} and {@code mobile_device_leases.input_hash}.
 * Idempotent; safe to re-enter. Fresh DBs may also be created by Hibernate ddl-auto.
 */
@Component("mobileSchemaMigration")
public class MobileSchemaMigration {
    private final boolean appliedPlatform;

    public MobileSchemaMigration(DataSource dataSource) throws Exception {
        this.appliedPlatform = migrate(dataSource);
    }

    public static boolean migrate(DataSource dataSource) throws Exception {
        try (Connection c = dataSource.getConnection()) {
            boolean changed = false;
            if (exists(c, "projects", null) && !exists(c, "projects", "platform")) {
                try (Statement s = c.createStatement()) {
                    s.execute("ALTER TABLE projects ADD platform VARCHAR(16) DEFAULT 'WEB'");
                }
                changed = true;
            }
            if (exists(c, "projects", "platform")) {
                try (Statement s = c.createStatement()) {
                    s.executeUpdate("UPDATE projects SET platform = 'WEB' WHERE platform IS NULL OR TRIM(platform) = ''");
                }
            }
            changed |= ensureTable(c, """
                    CREATE TABLE mobile_apps (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      app_id VARCHAR(64) NOT NULL,
                      tenant_id VARCHAR(40) NOT NULL,
                      project_id VARCHAR(64) NOT NULL,
                      source VARCHAR(32) NOT NULL,
                      active_revision_id VARCHAR(64),
                      lifecycle VARCHAR(32) NOT NULL,
                      created_at TIMESTAMP NOT NULL,
                      CONSTRAINT uk_mobile_apps_app_id UNIQUE (app_id)
                    )
                    """);
            changed |= ensureTable(c, """
                    CREATE TABLE mobile_app_revisions (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      revision_id VARCHAR(64) NOT NULL,
                      app_id VARCHAR(64) NOT NULL,
                      tenant_id VARCHAR(40) NOT NULL,
                      project_id VARCHAR(64) NOT NULL,
                      source VARCHAR(32) NOT NULL,
                      package_name VARCHAR(256),
                      version_code BIGINT,
                      version_name VARCHAR(128),
                      min_sdk INT,
                      abi_list VARCHAR(512),
                      launch_activity VARCHAR(512),
                      wait_activity VARCHAR(512),
                      apk_blob_ref VARCHAR(512),
                      sha256 VARCHAR(64),
                      certificate_digest VARCHAR(128),
                      verification VARCHAR(32) NOT NULL,
                      observed_metadata_json VARCHAR(4000),
                      created_by VARCHAR(64),
                      created_at TIMESTAMP NOT NULL,
                      CONSTRAINT uk_mobile_app_revisions_rev UNIQUE (revision_id)
                    )
                    """);
            changed |= ensureTable(c, """
                    CREATE TABLE mobile_device_profiles (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      profile_revision_id VARCHAR(64) NOT NULL,
                      tenant_id VARCHAR(40) NOT NULL,
                      project_id VARCHAR(64) NOT NULL,
                      display_name VARCHAR(256),
                      runner_id VARCHAR(64),
                      device_id VARCHAR(64),
                      app_revision_id VARCHAR(64),
                      package_name VARCHAR(256),
                      capabilities_allowlist_json VARCHAR(4000),
                      reset_permission_policy_json VARCHAR(4000),
                      locale VARCHAR(64),
                      orientation VARCHAR(32),
                      timeouts_json VARCHAR(2000),
                      created_at TIMESTAMP NOT NULL,
                      CONSTRAINT uk_mobile_device_profiles_rev UNIQUE (profile_revision_id)
                    )
                    """);
            changed |= ensureTable(c, """
                    CREATE TABLE mobile_devices (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      device_id VARCHAR(64) NOT NULL,
                      tenant_id VARCHAR(40) NOT NULL,
                      host_id VARCHAR(64) NOT NULL,
                      serial_fingerprint VARCHAR(128) NOT NULL,
                      serial_short VARCHAR(32),
                      display_name VARCHAR(256),
                      model VARCHAR(128),
                      api_level INT,
                      abi VARCHAR(64),
                      authorized_state VARCHAR(32) NOT NULL,
                      readiness VARCHAR(32) NOT NULL,
                      busy VARCHAR(32) NOT NULL,
                      last_seen_at TIMESTAMP,
                      fence_seq BIGINT NOT NULL DEFAULT 0,
                      created_at TIMESTAMP NOT NULL,
                      CONSTRAINT uk_mobile_devices_device_id UNIQUE (device_id),
                      CONSTRAINT uk_mobile_devices_host_serial UNIQUE (host_id, serial_fingerprint)
                    )
                    """);
            changed |= ensureTable(c, """
                    CREATE TABLE mobile_device_leases (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      lease_id VARCHAR(64) NOT NULL,
                      device_id VARCHAR(64) NOT NULL,
                      tenant_id VARCHAR(40) NOT NULL,
                      job_id VARCHAR(64),
                      attempt_id VARCHAR(64),
                      input_hash VARCHAR(128),
                      generation BIGINT NOT NULL,
                      fence_token BIGINT NOT NULL,
                      expires_at TIMESTAMP,
                      heartbeat_at TIMESTAMP,
                      session_ref VARCHAR(128),
                      owned_process_ref VARCHAR(128),
                      cleanup_status VARCHAR(32) NOT NULL,
                      state VARCHAR(32) NOT NULL,
                      created_at TIMESTAMP NOT NULL,
                      CONSTRAINT uk_mobile_device_leases_lease_id UNIQUE (lease_id),
                      CONSTRAINT uk_mobile_device_leases_active_device UNIQUE (device_id)
                    )
                    """);
            // M1-04 additive columns on existing installs
            changed |= ensureColumn(c, "mobile_devices", "fence_seq",
                    "ALTER TABLE mobile_devices ADD fence_seq BIGINT DEFAULT 0 NOT NULL");
            changed |= ensureColumn(c, "mobile_device_leases", "input_hash",
                    "ALTER TABLE mobile_device_leases ADD input_hash VARCHAR(128)");
            return changed;
        }
    }

    private static boolean ensureColumn(Connection c, String table, String column, String alterSql) throws Exception {
        if (!exists(c, table, null) || exists(c, table, column)) {
            return false;
        }
        try (Statement s = c.createStatement()) {
            s.execute(alterSql);
        }
        return true;
    }

    private static boolean ensureTable(Connection c, String createSql) throws Exception {
        String table = createSql.trim().split("\\s+")[2];
        if (exists(c, table, null)) {
            return false;
        }
        try (Statement s = c.createStatement()) {
            s.execute(createSql);
        }
        return true;
    }

    private static boolean exists(Connection c, String table, String column) throws Exception {
        for (String t : new String[]{table, table.toUpperCase()}) {
            try (ResultSet rs = column == null
                    ? c.getMetaData().getTables(null, null, t, null)
                    : c.getMetaData().getColumns(null, null, t, null)) {
                while (rs.next()) {
                    if (column == null || column.equalsIgnoreCase(rs.getString("COLUMN_NAME"))) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    public boolean appliedPlatform() {
        return appliedPlatform;
    }

    @Component
    static class JpaWaitsForMobileMigration extends EntityManagerFactoryDependsOnPostProcessor {
        JpaWaitsForMobileMigration() {
            super("mobileSchemaMigration");
        }
    }
}
