ALTER TABLE portal_users ADD COLUMN IF NOT EXISTS approval_status VARCHAR(32) DEFAULT 'PENDING_APPROVAL';
ALTER TABLE portal_users ADD COLUMN IF NOT EXISTS approved_at TIMESTAMP;
ALTER TABLE portal_users ADD COLUMN IF NOT EXISTS approved_by_user_id BIGINT;

-- Account-scoped jobs: nullable project + flag
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS account_scoped BOOLEAN DEFAULT FALSE;
